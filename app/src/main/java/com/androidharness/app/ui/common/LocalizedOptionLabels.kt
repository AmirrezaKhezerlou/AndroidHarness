@androidx.compose.runtime.Composable
internal fun localizedOption(value: String): String =
    androidx.compose.ui.platform.LocalContext.current.localizedOptionLabel(value)

/** Reasoning Ultra expresses effort, while Caveman Ultra expresses brevity. */
@androidx.compose.runtime.Composable
internal fun localizedThinkingOption(value: String): String =
    if (value == "Ultra") androidx.compose.ui.res.stringResource(R.string.ui_reasoning_ultra)
    else localizedOption(value)
